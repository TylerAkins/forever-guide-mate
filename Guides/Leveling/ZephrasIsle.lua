-- Skyborne starter path for Zephras Isle, levels 1-14.
-- Quest list, chains, and coordinates:
-- https://www.wowhead.com/forever/zone=16593/zephras-isle#quests
-- https://www.wowhead.com/forever/zone=16593/zephras-isle#starts-quest
-- Wowhead's quest pages label the island zone 16593. Guide pins use uiMap
-- 2521, the Zephras Isle map already used by the travel network. The
-- percentage coordinates match that map: Valanaar sits in the south, beside
-- the skycutter docks.
-- Secrets of Undeath (78197) is omitted. It is a level 22 priest quest, not
-- part of this starter path.
-- Camping 101 steps that require a profession skill of 20 are omitted.
-- The Great Outdoors and Camping 101: Cooking stay, because they finish at
-- the campfire and the cooking trainer.
-- Ripped Missive (94490) starts from the item dropped by Commander Haalien.
-- Rusty Gadget is an unlinked Wind Hollow drop, so it is mentioned on the
-- Wind Hollow steps instead of tracked as its own quest.
-- The Horde skycutter arrives in Mulgore (uiMap 1412, Wowhead area 215).
-- The Alliance skycutter arrives on the Alterac Mountains map (uiMap 1416,
-- Wowhead area 36); the quest text calls that arrival Dalaran.
-- Coordinates have not been validated in the Forever client.
-- UnitRace reports Alliance Skyborne as 95 and Horde Skyborne as 96.
-- Wowhead's race bitmask does not use those client ids.

